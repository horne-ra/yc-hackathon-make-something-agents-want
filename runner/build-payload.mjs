// Development-only build. esbuild is supplied by the existing locked tsx install.
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
const require=createRequire(import.meta.url);
const {build}=require(require.resolve('esbuild',{paths:[require.resolve('tsx')]}));
const result=await build({entryPoints:[fileURLToPath(new URL('./main.ts',import.meta.url))],bundle:true,platform:'node',target:'node22',format:'esm',write:false,banner:{js:"import { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);"},minify:true});
const text=result.outputFiles[0].text;
await writeFile(new URL('./payload.ts',import.meta.url),'// Generated by node runner/build-payload.mjs; no secrets. Rebuild after runner/core changes.\nexport const runnerPayloadBase64 = '+JSON.stringify(gzipSync(text).toString('base64'))+';\n');
console.log(`Built self-contained runner: ${Buffer.byteLength(text)} bytes; gzip/base64 ${gzipSync(text).toString('base64').length} bytes`);
