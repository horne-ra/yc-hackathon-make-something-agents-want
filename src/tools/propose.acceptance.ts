import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { auditServer } from './audit.js';
import { proposePatch, type ProposalAttempt } from './propose.js';
import { hashTools, PatchSpecSchema } from '../core/index.js';
process.loadEnvFile('.env');
const server_url = process.env.TRACKR_URL!;
const audit = await auditServer({ server_url });
assert.deepEqual(audit.findings.slice(0, 3).map(f => [f.id, f.kind]), [['F1', 'sibling_overlap'], ['F2', 'unconstrained_string'], ['F3', 'payload_control_undocumented']]);
assert.equal(audit.findings.find(f => f.id === 'F2')?.param, 'status');
assert.equal(audit.findings.find(f => f.id === 'F2')?.tool, 'list_issues');
assert.equal(audit.findings.find(f => f.id === 'F3')?.param, 'include_comments');
assert(audit.server_version.startsWith('trackr-demo-001@'));
console.log(`PASS live audit: F1–F3, version=${audit.server_version}, static_tool_tokens=${audit.static_tool_tokens}`);
const source_files = await Promise.all(['src/tools.ts', 'src/validation.ts', 'src/handlers.ts'].map(async path => ({ path, content: await readFile(`/Users/ransomhorne/Documents/trackr/${path}`, 'utf8') })));
const attempts: ProposalAttempt[] = [];
const patch = await proposePatch({ audit, source_files, finding_ids: ['F1', 'F2', 'F3'], style: 'compact' }, { onAttempt: async attempt => { attempts.push(attempt); await writeFile('src/tools/propose.attempts.json', JSON.stringify({ audit, attempts }, null, 2) + '\n'); console.log(`PROPOSAL attempt ${attempt.attempt}: ${attempt.status}${attempt.error ? ` (${attempt.error})` : ''}`); } });
PatchSpecSchema.parse(patch);
assert(patch.wire_ops.every(op => ['set_tool_description', 'set_param_description'].includes(op.op)));
assert.equal(hashTools(patch.candidate_tools), patch.candidate_tools_hash);
await writeFile('/private/tmp/axlint-phase2-proposed-patch-v2.json', JSON.stringify(patch, null, 2) + '\n');
await writeFile('src/tools/propose.live-evidence.json', JSON.stringify({ audit, patch, attempts }, null, 2) + '\n');
console.log(`PASS compact proposal: ${patch.wire_ops.length} description ops, ${patch.source_edits.length} deterministic edits, ${patch.warnings?.length ?? 0} warnings, static ${patch.static_tool_tokens.before} → ${patch.static_tool_tokens.after}`);
console.log(`PATCH /private/tmp/axlint-phase2-proposed-patch-v2.json baseline=${patch.base_server_version} hash=${patch.base_tools_hash}`);
